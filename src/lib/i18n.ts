const BROWSER_LANG_MAP: Record<string, Locale> = {
  en: "en", es: "es", fr: "fr", de: "de", it: "it", pt: "pt",
  ja: "ja", zh: "zh", ko: "ko", ru: "ru", ca: "ca", nl: "nl", ar: "ar",
};

export function detectBrowserLocale(): Locale {
  if (typeof navigator === "undefined") return "en";
  const langs = navigator.languages ?? [navigator.language];
  for (const lang of langs) {
    const code = lang.split("-")[0].toLowerCase();
    if (code in BROWSER_LANG_MAP) return BROWSER_LANG_MAP[code];
  }
  return "en";
}

// Map browser language to Whisper transcription language value
const BROWSER_TO_WHISPER_LANG: Record<string, string> = {
  en: "english", es: "spanish", fr: "french", de: "german", it: "italian",
  pt: "portuguese", ja: "japanese", zh: "chinese", ko: "korean",
  ru: "russian", ca: "catalan", nl: "dutch", ar: "arabic",
};

export function detectBrowserWhisperLang(): string {
  if (typeof navigator === "undefined") return "";
  const langs = navigator.languages ?? [navigator.language];
  for (const lang of langs) {
    const code = lang.split("-")[0].toLowerCase();
    if (code in BROWSER_TO_WHISPER_LANG) return BROWSER_TO_WHISPER_LANG[code];
  }
  return "";
}

